export function downloadProjectZip(params) {
  const files = generateProjectFiles(params);
  const safeSlug = (params.user_name || params.project_type || 'omniswarm')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '') || 'project';
  
  const filename = `${safeSlug}-app.zip`;
  downloadZipFile(filename, files);
  return { filename, count: files.length };
}
